#!/usr/bin/env python3
"""Small original PNG fixtures, including filters, palettes, 16-bit and Adam7."""
import struct
import zlib
from pathlib import Path


def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data))


def png(w, h, depth, color, raw, extra=b'', interlace=0):
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, depth, color, 0, 0, interlace))+extra+chunk(b'IDAT', zlib.compress(raw))+chunk(b'IEND', b'')


def paeth(a, b, c):
    p = a+b-c
    return a if abs(p-a) <= abs(p-b) and abs(p-a) <= abs(p-c) else b if abs(p-b) <= abs(p-c) else c


def fixtures():
    w, h = 5, 5
    pixels = bytes(v for y in range(h) for x in range(w) for v in (x*51, y*49, (x+y)*27, (x+y)*29))
    raw = bytearray()
    for y in range(h):
        row = pixels[y*w*4:(y+1)*w*4]
        prev = pixels[(y-1)*w*4:y*w*4] if y else bytes(w*4)
        raw.append(y)
        for i, value in enumerate(row):
            a = row[i-4] if i >= 4 else 0
            b, c = prev[i], prev[i-4] if i >= 4 else 0
            prediction = (0, a, b, (a+b)//2, paeth(a,b,c))[y]
            raw.append((value-prediction) & 255)
    yield 'filters', w, h, png(w,h,8,6,raw), pixels
    adam = bytearray()
    for x0,y0,dx,dy in ((0,0,8,8),(4,0,8,8),(0,4,4,8),(2,0,4,4),(0,2,2,4),(1,0,2,2),(0,1,1,2)):
        for y in range(y0,h,dy):
            row = b''.join(pixels[(y*w+x)*4:(y*w+x+1)*4] for x in range(x0,w,dx))
            if row:
                adam.append(0)
                adam.extend(row)
    yield 'adam7', w,h,png(w,h,8,6,adam,interlace=1),pixels
    palette = chunk(b'PLTE',bytes((255,0,0,0,255,0,0,0,255)))+chunk(b'tRNS',bytes((0,128,255)))
    yield 'palette',3,1,png(3,1,2,3,b'\0\x18',palette),bytes((255,0,0,0,0,255,0,128,0,0,255,255))
    yield 'gray',3,1,png(3,1,1,0,b'\0\xa0'),bytes((255,255,255,255,0,0,0,255,255,255,255,255))
    yield 'rgba16',1,1,png(1,1,16,6,b'\0\x12\x34\x56\x78\x9a\xbc\xde\xf0'),bytes((0x12,0x56,0x9a,0xde))


if __name__ == '__main__':
    out = ['/* Generated by tests/make_png_fixtures.py; original synthetic images. */']
    for name,w,h,data,rgba in fixtures():
        for suffix,contents in (('png',data),('rgba',rgba)):
            out.append('static const unsigned char png_'+name+'_'+suffix+'[]={'+','.join(str(x) for x in contents)+'};')
    for name, data in (
        ('inflate_budget', png(1,1,8,6,bytes(9*1024*1024))),
        ('oversized', png(1025,1,8,6,b'\0\0\0\0\0')),
        ('invalid_deflate', b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',1,1,8,6,0,0,0))+chunk(b'IDAT',b'not deflate')+chunk(b'IEND',b'')),
    ):
        out.append('static const unsigned char png_'+name+'[]={'+','.join(str(x) for x in data)+'};')
    Path(__file__).with_name('png_texture_fixtures.h').write_text('\n'.join(out)+'\n')
