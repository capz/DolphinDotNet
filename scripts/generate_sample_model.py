#!/usr/bin/env python3
"""Generate the original Fox ship glTF and embed a converted DNMD package."""
import base64,json,struct,subprocess,tempfile,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1];folder=root/'samples/Fox/Assets';folder.mkdir(exist_ok=True)
positions=[0,.25,-1.8,-.25,0,.6,.25,0,.6, 0,.25,-1.8,0,.55,.2,-.25,0,.6,
 0,.25,-1.8,.25,0,.6,0,.55,.2, -.2,0,-.6,-1.65,-.12,.65,-.15,0,.45,
 .2,0,-.6,.15,0,.45,1.65,-.12,.65, 0,.5,.1,0,1,.8,0,0,.65]
blob=bytearray();views=[];accessors=[]
def attribute(values,kind,count,components):
 offset=len(blob);blob.extend(struct.pack('<'+'f'*len(values),*values));views.append({'buffer':0,'byteOffset':offset,'byteLength':len(values)*4})
 accessors.append({'bufferView':len(views)-1,'componentType':5126,'count':count,'type':kind})
 return len(accessors)-1
p=attribute(positions,'VEC3',len(positions)//3,3)
n=attribute([0,1,0]*(len(positions)//3),'VEC3',len(positions)//3,3)
t=attribute([0,.5,1],'SCALAR',3,1)
v=attribute([0,0,0,0,.15,0,0,0,0],'VEC3',3,3)
gltf={'asset':{'version':'2.0','generator':'DolphinDotNet original sample'},'scene':0,'scenes':[{'nodes':[0]}],
'nodes':[{'name':'Ship','mesh':0}],'buffers':[{'byteLength':len(blob),'uri':'data:application/octet-stream;base64,'+base64.b64encode(blob).decode()}],
'bufferViews':views,'accessors':accessors,'materials':[{'pbrMetallicRoughness':{'baseColorFactor':[.45,.75,1,1],'metallicFactor':0,'roughnessFactor':1}}],
'meshes':[{'primitives':[{'attributes':{'POSITION':p,'NORMAL':n},'material':0}]}],
'animations':[{'name':'Hover','samplers':[{'input':t,'output':v,'interpolation':'LINEAR'}],'channels':[{'sampler':0,'target':{'node':0,'path':'translation'}}]}]}
source=folder/'ship.gltf';source_text=json.dumps(gltf,indent=2)+'\n'
checking='--check' in sys.argv
if checking:assert source.read_text()==source_text,'ship.gltf is stale'
else:source.write_text(source_text)
temporary=tempfile.TemporaryDirectory();package=Path(temporary.name)/'ship.dndmodel'
subprocess.run(['dotnet','run','--project',str(root/'tools/DolphinDotNet.Assets'),'-c','Release','--','model',str(source),str(package)],check=True)
data=package.read_bytes();lines=[','.join(str(b) for b in data[i:i+32]) for i in range(0,len(data),32)]
generated=('// Original ship, generated by scripts/generate_sample_model.py.\ninternal static class ShipModel\n{\n    internal static readonly byte[] Package=new byte[]{\n        '+',\n        '.join(lines)+'\n    };\n}\n')
destination=root/'samples/Fox/ShipModel.g.cs'
if checking:assert destination.read_text()==generated,'ShipModel.g.cs is stale'
else:destination.write_text(generated)
temporary.cleanup()
print(f'Embedded {len(data)} bytes, one original mesh and Hover animation.')
