#!/usr/bin/env python3
"""Original two-material imported quad: texture-alpha cutout plus raster color.

Rebuild with the existing glTF importer; package formats and importers are unchanged.
The ShaderDemo uses this fixture for default/effect/default visual acceptance.
"""
import base64
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import zlib

ROOT=Path(__file__).resolve().parents[1]

def generate():
    blob=bytearray();views=[];accessors=[]
    def attribute(values,kind,components):
        offset=len(blob);blob.extend(struct.pack('<'+'f'*len(values),*values))
        views.append(dict(buffer=0,byteOffset=offset,byteLength=len(values)*4))
        accessors.append(dict(bufferView=len(views)-1,componentType=5126,count=len(values)//components,type=kind))
        return len(accessors)-1
    primitives=[]
    for material,(left,right,intensity) in enumerate(((-78,-2,.8),(2,78,.4))):
        xy=((left,105),(right,105),(right,127),(left,105),(right,127),(left,127))
        positions=[c for x,y in xy for c in (x/240,(240-y)/240,0)]
        primitives.append(dict(attributes={
            'POSITION':attribute(positions,'VEC3',3),
            'NORMAL':attribute([0,0,1]*6,'VEC3',3),
            'TEXCOORD_0':attribute([c for x,y in xy for c in ((x-left)/(right-left),(y-105)/22)],'VEC2',2),
            'COLOR_0':attribute([intensity,intensity,intensity,1]*6,'VEC4',4)},material=material))
    def chunk(kind,data):
        return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data))
    rgba=b''.join(b'\0'+b''.join(bytes((255,255,255,0 if x<2 else 255)) for x in range(8)) for y in range(4))
    png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',8,4,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(rgba))+chunk(b'IEND',b'')
    source=dict(asset=dict(version='2.0',generator='DolphinDotNet original model effect fixture'),
        extensionsUsed=['KHR_materials_unlit'],scene=0,scenes=[dict(nodes=[0])],nodes=[dict(name='Panels',mesh=0)],
        buffers=[dict(byteLength=len(blob),uri='data:application/octet-stream;base64,'+base64.b64encode(blob).decode())],
        bufferViews=views,accessors=accessors,
        images=[dict(uri='data:image/png;base64,'+base64.b64encode(png).decode())],
        samplers=[dict(magFilter=9728,minFilter=9728,wrapS=33071,wrapT=33071)],textures=[dict(source=0,sampler=0)],
        materials=[dict(name='Alpha cutout',alphaMode='MASK',alphaCutoff=.5,doubleSided=True,
            pbrMetallicRoughness=dict(baseColorTexture=dict(index=0)),extensions={'KHR_materials_unlit':{}}),
            dict(name='Raster only',doubleSided=True,extensions={'KHR_materials_unlit':{}})],
        meshes=[dict(primitives=primitives)])
    with tempfile.TemporaryDirectory() as folder:
        path=Path(folder);gltf=path/'panels.gltf';package=path/'panels.dndmodel'
        gltf.write_text(json.dumps(source))
        subprocess.run(['dotnet','run','--project',str(ROOT/'tools/DolphinDotNet.Assets'),'-c','Release','--',
                        'model',str(gltf),str(package)],check=True)
        data=package.read_bytes()
    lines=[','.join(str(b) for b in data[i:i+32]) for i in range(0,len(data),32)]
    generated=('// Original synthetic geometry, generated by scripts/generate_model_effect_fixture.py.\n'
        'internal static class ImportedPanels\n{\n    internal static readonly byte[] Package=new byte[]{\n        '+
        ',\n        '.join(lines)+'\n    };\n}\n')
    destination=ROOT/'samples/ShaderDemo/ImportedPanels.g.cs'
    if '--check' in sys.argv:
        if destination.read_text()!=generated:raise AssertionError('ImportedPanels.g.cs is stale')
    else:destination.write_text(generated)
    print(f'Imported model fixture: {len(data)} bytes, two materials and texture-alpha cutout.')

if __name__=='__main__':generate()
