using System.Text;

namespace DolphinDotNet.SaveImage;

public static class SourceOutput
{
    public static string Generate(byte[] bytes, string ns, string className, string member)
    {
        static string Identifier(string value)
        {
            if (value.Length == 0 || !(char.IsAsciiLetter(value[0]) || value[0] == '_') ||
                value.Any(c => !(char.IsAsciiLetterOrDigit(c) || c == '_')))
                throw new ArgumentException("Source names must be valid ASCII C# identifiers.");
            return "@" + value; // Escaping also handles C# keywords safely.
        }
        var namespaceName = string.Join(".", ns.Split('.').Select(Identifier));
        var type = Identifier(className);
        var name = Identifier(member);
        var text = new StringBuilder("// Generated by dnd-save-image. Each property access creates a new byte array.\n");
        text.Append("namespace ").Append(namespaceName).Append("\n{\n    public static class ").Append(type)
            .Append("\n    {\n        public static byte[] ").Append(name).Append(" => new byte[]\n        {\n");
        for (int i = 0; i < bytes.Length; i += 16)
        {
            text.Append("            ");
            for (int j = i; j < Math.Min(i + 16, bytes.Length); j++) text.Append("0x").Append(bytes[j].ToString("X2")).Append(", ");
            text.Append('\n');
        }
        return text.Append("        };\n    }\n}\n").ToString();
    }
}
