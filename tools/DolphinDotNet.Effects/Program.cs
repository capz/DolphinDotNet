using DolphinDotNet.Effects;
try {
    if(args.Length<2||args.Length>4)throw new ArgumentException("Usage: dnd-effects INPUT.json OUTPUT.dndfx [OUTPUT.g.cs CLASS_NAME]");
    if(new FileInfo(args[0]).Length>65536)throw new ArgumentException("Graph exceeds 64 KiB.");
    var result=EffectCompiler.Compile(File.ReadAllText(args[0]));
    string className=args.Length==4?args[3]:"CompiledEffect";
    if(className.Length==0||!(char.IsAsciiLetter(className[0])||className[0]=='_')||className.Any(c=>!char.IsAsciiLetterOrDigit(c)&&c!='_'))throw new ArgumentException("Invalid generated class name.");
    Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[1]))!);
    File.WriteAllBytes(args[1],result.Package);
    if(args.Length>=3)Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[2]))!);
    if(args.Length>=3)File.WriteAllText(args[2],"// Generated by DolphinDotNet.Effects.\ninternal static class "+className+" { internal static readonly byte[] Package={"+string.Join(",",result.Package)+"}; }\n");
    Console.WriteLine($"TEV: {result.StageCount}/16 stages, {result.UniformCount}/4 uniforms, {result.PeakRegisters}/4 registers; texture={result.RequiresTexture}");
    return 0;
} catch(Exception e){Console.Error.WriteLine("DND-FX: "+e.Message);return 1;}
